import { ref, watchEffect } from "vue";

// Spanish text is the key and the fallback; `en` maps it to English.
// Placeholders: t("{n} objetos", { n: 3 }).
export type Lang = "es" | "en";
const KEY = "fd-lang";

const saved = (() => {
  try {
    return localStorage.getItem(KEY);
  } catch {
    return null;
  }
})();
export const lang = ref<Lang>(saved === "es" || saved === "en" ? saved : globalThis.navigator?.language?.startsWith("es") ? "es" : "en");

watchEffect(() => {
  try {
    localStorage.setItem(KEY, lang.value);
  } catch {}
  if (globalThis.document) document.documentElement.lang = lang.value;
});

export function t(s: string, vars: Record<string, string | number> = {}) {
  const out = lang.value === "en" ? en[s] ?? s : s;
  return out.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

